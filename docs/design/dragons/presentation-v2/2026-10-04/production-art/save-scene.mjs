import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const [jobFile, rawPath, sharpPath] = process.argv.slice(2);
const sharp=createRequire(import.meta.url)(sharpPath);
const job=JSON.parse(fs.readFileSync(jobFile,'utf8'));
const base=path.dirname(path.dirname(jobFile));
const root=path.resolve(base,'../../../../../..');
const original=path.join(base,'originals/scenes',job.id+'.png');
const final=path.join(root,job.runtime);
fs.mkdirSync(path.dirname(original),{recursive:true});fs.mkdirSync(path.dirname(final),{recursive:true});
fs.copyFileSync(rawPath,original);
await sharp(original).resize({width:720,height:960,fit:'inside',withoutEnlargement:true}).webp({quality:88}).toFile(final);
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const metadata=await sharp(final).metadata();
const record={...job,source:'image_gen',rawOutput:rawPath,original:path.relative(root,original).replaceAll('\\','/'),originalSha256:sha(original),runtimeSha256:sha(final),dimensions:[metadata.width,metadata.height],bytes:fs.statSync(final).size,references:job.refs.map(p=>({path:path.relative(root,p).replaceAll('\\','/'),sha256:sha(p)})),conversion:'resize inside 720x960, no crop, WebP quality88; no semantic editing',generatedAt:new Date().toISOString()};
fs.mkdirSync(path.join(base,'scene-records'),{recursive:true});fs.writeFileSync(path.join(base,'scene-records',job.id+'.json'),JSON.stringify(record,null,2)+'\n');
console.log(JSON.stringify({id:job.id,runtime:job.runtime,dimensions:record.dimensions,bytes:record.bytes}));
